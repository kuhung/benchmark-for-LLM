import { BenchmarkSession, StatsSummary } from './benchmark/types'

export function generateMarkdownReport(session: BenchmarkSession): string {
  const date = new Date(session.timestamp).toISOString().replace('T', ' ').slice(0, 19)
  const lines: string[] = []

  lines.push('# LLM Benchmark Report')
  lines.push('')
  lines.push(`> Generated: ${date}`)
  lines.push('')

  lines.push('## Test Configuration')
  lines.push('')
  lines.push(`- **Repeat Count**: ${session.config.repeatCount}`)
  lines.push(`- **Max Tokens**: ${session.config.maxTokens}`)
  lines.push(`- **Concurrency Levels**: ${session.config.concurrencyLevels.join(', ')}`)
  lines.push(`- **Prompt**: ${session.config.prompt.length > 80 ? session.config.prompt.slice(0, 80) + '...' : session.config.prompt}`)
  lines.push('')

  lines.push('## Endpoints')
  lines.push('')
  for (const r of session.results) {
    lines.push(`- **${r.endpoint.name}**: \`${r.endpoint.baseUrl}\` / model: \`${r.endpoint.modelId}\``)
  }
  lines.push('')

  lines.push('## Performance Summary (Single Concurrency)')
  lines.push('')
  lines.push('| Endpoint | TTFT P50 (ms) | TTFT IQR | TPS P50 | TPS IQR | ITL P95 (ms) | E2E P50 (ms) | Success |')
  lines.push('|----------|---------------|----------|---------|---------|--------------|--------------|---------|')

  for (const r of session.results) {
    const m = r.singleConcurrency
    lines.push(
      `| ${r.endpoint.name} ` +
      `| ${m.ttft.median.toFixed(0)} ` +
      `| ${formatIQR(m.ttft)} ` +
      `| ${m.tps.median.toFixed(1)} ` +
      `| ${formatIQR(m.tps)} ` +
      `| ${m.itl.p95.toFixed(1)} ` +
      `| ${m.e2eLatency.median.toFixed(0)} ` +
      `| ${m.successRate.toFixed(0)}% |`
    )
  }
  lines.push('')

  const hasConcurrency = session.results.some(r => r.concurrencyResults.length > 1)
  if (hasConcurrency) {
    lines.push('## Concurrency Scaling')
    lines.push('')
    lines.push('| Endpoint | Concurrency | Req Throughput (req/s) | Token Throughput (t/s) | TPS P50 | TTFT P50 (ms) |')
    lines.push('|----------|-------------|----------------------|----------------------|---------|---------------|')

    for (const r of session.results) {
      for (const cr of r.concurrencyResults) {
        lines.push(
          `| ${r.endpoint.name} ` +
          `| ${cr.concurrency} ` +
          `| ${cr.requestThroughput.toFixed(2)} ` +
          `| ${cr.tokenThroughput.toFixed(1)} ` +
          `| ${cr.metrics.tps.median.toFixed(1)} ` +
          `| ${cr.metrics.ttft.median.toFixed(0)} |`
        )
      }
    }
    lines.push('')
  }

  if (session.results.some(r => r.score)) {
    lines.push('## Radar Scores (0-100)')
    lines.push('')
    lines.push('| Endpoint | Speed | Responsiveness | Smoothness | Scalability | Stability | Overall |')
    lines.push('|----------|-------|----------------|------------|-------------|-----------|---------|')
    for (const r of session.results) {
      if (!r.score) continue
      const s = r.score
      lines.push(
        `| ${r.endpoint.name} ` +
        `| ${s.speed.toFixed(0)} ` +
        `| ${s.responsiveness.toFixed(0)} ` +
        `| ${s.smoothness.toFixed(0)} ` +
        `| ${s.scalability.toFixed(0)} ` +
        `| ${s.stability.toFixed(0)} ` +
        `| ${s.overall.toFixed(0)} |`
      )
    }
    lines.push('')
  }

  lines.push('---')
  lines.push('')
  lines.push('*Generated by [LLM Bench](https://github.com/kuhung/benchmark-for-LLM)*')

  return lines.join('\n')
}

function formatIQR(stats: StatsSummary): string {
  const q1 = stats.median - stats.stdDev * 0.6745
  const q3 = stats.median + stats.stdDev * 0.6745
  return `${Math.max(0, q1).toFixed(0)}-${q3.toFixed(0)}`
}
